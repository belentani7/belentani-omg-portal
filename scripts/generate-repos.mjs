#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const user = "belentani7";

const raw = JSON.parse(
  execFileSync(
    "gh",
    [
      "repo",
      "list",
      user,
      "--limit",
      "500",
      "--json",
      "name,description,isPrivate,isFork,isArchived,isEmpty,primaryLanguage,stargazerCount,updatedAt,url,homepageUrl,repositoryTopics",
    ],
    { maxBuffer: 40 * 1024 * 1024 },
  ).toString(),
);

const CATEGORY_RULES = [
  ["agents", /agent|orquest|orchestr|router|llm|model|swarm|guard|autonomous|aion|omni/i],
  ["devtools", /tool|cli|skill|dev|code|runtime|environment|linux|docker|mcp|terminal|forge/i],
  ["creative", /music|audio|voice|voz|creative|art|design|visual|3d|webgl|video|fashion|arte|duck|judas|suno|singer|bpm/i],
  ["impact", /educ|school|lingua|aprende|mentor|migrant|salud|health|psico|cuidar|social|academy|curso|william|manos/i],
  ["protocols", /evidence|proof|validation|verify|audit|security|secure|credential|compliance|risk|governance|qbp|compass|ledger/i],
  ["products", /store|shop|web|app|portfolio|hub|portal|platform|saas|cv|travel|restaurant|entrenador|client/i],
];

const CATEGORY_OVERRIDES = {
  "secure-t": "impact",
  "belentani-omg-portal": "devtools",
  "belentani7": "products",
  "belentani.es": "creative",
  "belentani7.github.io": "creative",
  "belentani-docs": "devtools",
  "registro-proyectos-2026": "products",
  "backend_aportaciones_software01": "agents",
  "backend_aportaciones_software02": "devtools",
  "backend_aportaciones_software03": "creative",
  "backend_aportaciones_software04": "products",
  "ManosAbiertas": "impact",
  "WILLIAMSCHOOL": "impact",
  "lingua-aberta": "impact",
  "aprende-brasil": "impact",
  "judas-experience": "creative",
  "heyduck": "creative",
  "Duck-Omega": "creative",
  "CARQUIDEC": "creative",
  "Belentani.cv-ai": "products",
  "omniagent": "agents",
  "agent-orchestration-machine": "agents",
  "DEV-TOOLKIT": "devtools",
};

function inferCategory(repo) {
  if (CATEGORY_OVERRIDES[repo.name]) return CATEGORY_OVERRIDES[repo.name];
  if (repo.isArchived || repo.isEmpty || /backup|snapshot|archivo|premium/i.test(repo.name)) {
    return "archive";
  }
  const text = [
    repo.name,
    repo.description ?? "",
    ...(repo.repositoryTopics ?? []).map(topic => topic.name),
  ].join(" ");
  for (const [category, pattern] of CATEGORY_RULES) {
    if (pattern.test(text)) return category;
  }
  return "products";
}

const repos = raw
  .map(repo => {
    const language = repo.primaryLanguage?.name ?? null;
    return {
      name: repo.name,
      desc: repo.description ?? "",
      url: repo.url,
      homepage: repo.homepageUrl || "",
      private: Boolean(repo.isPrivate),
      fork: Boolean(repo.isFork),
      archived: Boolean(repo.isArchived),
      empty: Boolean(repo.isEmpty),
      language,
      stars: repo.stargazerCount,
      updated: repo.updatedAt,
      topics: (repo.repositoryTopics ?? []).map(topic => topic.name),
      category: inferCategory(repo),
      live: Boolean(repo.homepageUrl),
    };
  })
  .sort((a, b) => b.updated.localeCompare(a.updated));

const byLanguage = {};
for (const repo of repos) {
  const key = repo.language ?? "Sin lenguaje";
  byLanguage[key] = (byLanguage[key] ?? 0) + 1;
}

const totals = {
  total: repos.length,
  public: repos.filter(repo => !repo.private).length,
  private: repos.filter(repo => repo.private).length,
  live: repos.filter(repo => repo.live).length,
  archived: repos.filter(repo => repo.archived).length,
  forks: repos.filter(repo => repo.fork).length,
  languages: Object.keys(byLanguage).length,
  byLanguage,
};

const payload = {
  generated: new Date().toISOString().slice(0, 10),
  owner: user,
  totals,
  repos,
};

const js = `// Generated by scripts/generate-repos.mjs. Do not edit by hand.
window.OMG_REPOS = ${JSON.stringify(payload, null, 2)};
`;

writeFileSync(path.join(root, "data", "repos.js"), js, "utf8");
writeFileSync(
  path.join(root, "data", "repos.json"),
  `${JSON.stringify(payload, null, 2)}\n`,
  "utf8",
);

console.log(
  `repos: ${totals.total} total · ${totals.public} public · ${totals.private} private · ${totals.live} live · ${totals.archived} archived`,
);

